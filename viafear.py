class ViafearPlugin(BasePlugin):
    def on_plugin_load(self):
        self.add_on_send_message_hook()
        self.logger.info("viafear loaded")

    def on_plugin_unload(self):
        pass

    def create_settings(self) -> List[Any]:
        return [
            Header(text="viafear"),
            Text(text="Команды", subtext="/adot — случайный еврейский анекдот", icon="msg_info"),
            Text(text="Визуал", subtext="ник + fear, подпись @viafear", icon="msg_info"),
        ]

    def on_send_message_hook(self, account: int, params: Any) -> HookResult:
        msg = getattr(params, "message", None)
        if not isinstance(msg, str):
            return HookResult()
        text = msg.strip()
        if text == "/adot" or text.startswith("/adot "):
            joke = random.choice(JOKES)
            params.message = joke
            return HookResult(strategy=HookStrategy.MODIFY, params=params)
        return HookResult()
